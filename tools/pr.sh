#!/bin/sh
# deckstack PR lifecycle — owns prs/<id>.md records and review verdicts.
#   sh tools/pr.sh submit <DS-XXX>                          (run INSIDE .worktrees/<DS-XXX> on branch ticket/<DS-XXX>)
#   sh tools/pr.sh review <DS-XXX> [--approve|--request-changes REASON]   (STEWARD ONLY, on main, DS_STEWARD=1)
#   sh tools/pr.sh merge <DS-XXX>                           (STEWARD ONLY, on main, DS_STEWARD=1)
#   sh tools/pr.sh list                                     (open PRs; either worktree)
# review/merge are steward-only: they require DS_STEWARD=1 (exported by tools/steward.sh)
# and refuse self-approval (reviewer identity == ticket owner). Workers hand off to the
# steward instead. Ticket metadata is owned by tools/tickets.py; the merge decision by
# the steward. See AGENTS.md and docs/AGENT-WORKFLOW.md.
set -eu
ROOT=$(CDPATH= cd -- "$(dirname -- "$0")/.." && pwd)
cd "$ROOT"
TICKETS="python3 $ROOT/tools/tickets.py"
TMP=$(mktemp -d)
trap 'rm -rf "$TMP"' EXIT

die() { echo "pr.sh: error: $*" >&2; exit 1; }
usage() {
  cat <<'USAGE'
usage:
  sh tools/pr.sh submit <DS-XXX>     # in the ticket worktree: checks, prs/<id>.md, state review, push to review
  sh tools/pr.sh review <DS-XXX> [--approve | --request-changes REASON]   # on main, STEWARD only (DS_STEWARD=1)
  sh tools/pr.sh merge <DS-XXX>      # on main, STEWARD only (DS_STEWARD=1): requires approved review
  sh tools/pr.sh list                # open PRs with ticket, owner, branch, verdict, ahead/behind

review/merge need DS_STEWARD=1 in the environment (tools/steward.sh exports it) and are
refused when the reviewer identity equals the ticket owner. Workers: hand off to the
steward — sh tools/steward.sh "review DS-XXX and merge if approved".
USAGE
}

main_branch() {
  if git show-ref --verify --quiet refs/heads/main; then echo main
  elif git show-ref --verify --quiet refs/heads/master; then echo master
  else echo ""; fi
}

require_main_worktree() {
  [ -d "$ROOT/.git" ] || die "run from the MAIN worktree ($ROOT)"
  MB=$(main_branch); [ -n "$MB" ] || die "no main/master branch"
  [ "$(git symbolic-ref --short HEAD)" = "$MB" ] || die "main worktree must be on branch $MB"
}

require_clean() {
  [ -z "$(git status --porcelain)" ] || die "working tree is dirty; commit or stash first (ignored files are fine)"
}

# R02: review/merge are steward-only. DS_STEWARD=1 must be in the environment (exported by
# tools/steward.sh when it launches the steward agent); the reviewer identity must not equal
# the ticket owner, so a worker can never approve its own PR by following the docs.
require_steward() { # id command-name
  rs_id=$1; rs_cmd=$2
  if [ "${DS_STEWARD:-0}" != "1" ]; then
    die "$rs_cmd is steward-only and requires DS_STEWARD=1 in the environment.
Workers must not review or merge — hand off to the steward instead:
  sh tools/steward.sh \"review $rs_id and merge if approved\"
(tools/steward.sh exports DS_STEWARD=1 for the steward agent)."
  fi
  rs_owner=$(field "$rs_id" owner 2>/dev/null || echo null)
  rs_reviewer=$(git config user.name 2>/dev/null || echo "${USER:-unknown}")
  if [ -n "$rs_owner" ] && [ "$rs_owner" != "null" ] && [ "$rs_reviewer" = "$rs_owner" ]; then
    die "reviewer '$rs_reviewer' is the ticket owner '$rs_owner' — self-approval is forbidden.
Hand the PR to the steward: sh tools/steward.sh \"review $rs_id and merge if approved\"."
  fi
}

# R01: push the main branch to the review remote and verify it landed (fail loudly).
push_main_to_review() { # main-branch
  pmb=$1
  git remote get-url review >/dev/null 2>&1 || die "no 'review' remote; run sh tools/setup-review-remote.sh on main first"
  if ! git push review "$pmb"; then
    die "push of $pmb to remote 'review' FAILED — main is NOT synced on review; inspect 'git remote -v' / .review.git and re-run"
  fi
  local_sha=$(git rev-parse "$pmb")
  remote_sha=$(git ls-remote review "refs/heads/$pmb" | awk '{print $1}')
  [ -n "$remote_sha" ] || die "verification failed: refs/heads/$pmb missing on remote 'review' after push"
  [ "$local_sha" = "$remote_sha" ] || die "verification failed: review $pmb=$remote_sha but local $pmb=$local_sha — push did not land; do not proceed"
  echo "pushed $pmb to review and verified remote sha $remote_sha"
}

# R08: pipe the message via stdin (git commit -F -) — no here-doc delimiter to break.
vibe_commit() {
  printf '%s\n\nGenerated by Mistral Vibe.\nCo-Authored-By: Mistral Vibe <vibe@mistral.ai>\n' "$1" | git commit -F -
}

field() { $TICKETS field "$1" "$2" 2>/dev/null; }

# R07: single-line placeholder fill, safe for any value (|, &, \, newlines) — plain
# Python string replace, value passed via the environment (never through sed patterns).
fill_line() { # file placeholder value
  FILL_FILE=$1 FILL_PH=$2 FILL_VAL=$3 python3 -c '
import os
p, ph, val = os.environ["FILL_FILE"], os.environ["FILL_PH"], os.environ["FILL_VAL"]
with open(p, encoding="utf-8") as f:
    s = f.read()
if ph not in s:
    raise SystemExit(f"pr.sh: placeholder {ph!r} not found in {p}")
with open(p, "w", encoding="utf-8") as f:
    f.write(s.replace(ph, val))
'
}

# multi-line placeholder fill from a file
fill_block() { # file placeholder blockfile
  f=$1; ph=$2; bf=$3
  awk -v ph="$ph" -v bf="$bf" '
    index($0, ph) { while ((getline line < bf) > 0) print line; close(bf); next }
    { print }
  ' "$f" > "$f.tmp" && mv "$f.tmp" "$f"
}

# extract a "## <heading>" body section from a markdown file
body_section() { # file heading
  awk -v h="## $2" '
    /^## / { insec = ($0 == h) ? 1 : 0; next }
    insec { print }
  ' "$1"
}

run_checks() { # worktree-root -> writes $TMP/checks.txt, returns check status
  local wt rc
  wt=$1
  rc=1
  if [ -f "$wt/tools/check.sh" ]; then
    # R03: check.sh validates the tree it is given (arg 1), i.e. this worktree — not main
    if sh "$wt/tools/check.sh" "$wt" > "$TMP/checks.log" 2>&1; then
      rc=0
      { echo "tools/check.sh in $wt: PASS (ALL GREEN)"; echo; echo '```'; tail -n 15 "$TMP/checks.log"; echo '```'; } > "$TMP/checks.txt"
    else
      rc=$?
      { echo "tools/check.sh in $wt: FAIL (rc!=0)"; echo; echo '```'; tail -n 25 "$TMP/checks.log"; echo '```'; } > "$TMP/checks.txt"
    fi
  else
    echo "tools/check.sh not present in $wt (cannot gate) — FAIL" > "$TMP/checks.txt"
  fi
  return "$rc"
}

ticket_block() { # id -> fills $TMP/acceptance.txt and $TMP/risks.txt from the ticket
  id=$1
  tf="$ROOT/tickets/$id.md"
  [ -f "$tf" ] || die "cannot find tickets/$id.md"
  {
    echo "acceptance (from tickets/$id.md metadata):"
    field "$id" acceptance | tr -d '[]"' | tr ',' '\n' | sed 's/^ */- /'
    echo
    echo "verification:"
    field "$id" verification | tr -d '[]"' | tr ',' '\n' | sed 's/^ */- /'
  } > "$TMP/acceptance.txt"
  body_section "$tf" "Risks" > "$TMP/risks.txt"
  [ -s "$TMP/risks.txt" ] || echo "(none recorded)" > "$TMP/risks.txt"
}

cmd_submit() {
  [ $# -ge 1 ] || { usage >&2; die "submit needs a ticket id"; }
  id=$1
  # R05: submit must run inside the MAIN repo's .worktrees/<id> on branch ticket/<id> —
  # not merely anywhere inside a git repo.
  common=$(git rev-parse --git-common-dir 2>/dev/null) || die "not inside a git repository; submit runs INSIDE the ticket worktree (.worktrees/$id)"
  case "$common" in /*) ;; *) common="$(pwd)/$common" ;; esac
  mainroot=$(dirname "$common")
  [ "$(pwd -P)" = "$mainroot/.worktrees/$id" ] || die "submit must run inside $mainroot/.worktrees/$id (you are in $(pwd -P)); cd $mainroot/.worktrees/$id first"
  MB=$(main_branch); [ -n "$MB" ] || die "no main/master branch"

  branch=$(git rev-parse --abbrev-ref HEAD)
  [ "$branch" = "ticket/$id" ] || die "HEAD is '$branch', expected ticket/$id (run inside .worktrees/$id)"
  require_clean
  state=$(field "$id" state) || die "no ticket $id"
  [ "$state" = "doing" ] || die "$id is '$state', expected doing"
  ahead=$(git rev-list --count "$MB..HEAD")
  [ "$ahead" -ge 1 ] || die "branch ticket/$id has no commits ahead of $MB"
  git log "$MB..HEAD" --format=%s | grep -q "ticket($id):" || die "no 'ticket($id):' commit subject in $MB..HEAD"
  git remote get-url review >/dev/null 2>&1 || die "no 'review' remote; run sh tools/setup-review-remote.sh on main first"

  echo "== submit $id: base $MB..HEAD ($ahead commit(s)) =="
  run_checks "$ROOT"
  cat "$TMP/checks.txt"

  base=$(git merge-base "$MB" HEAD)
  head=$(git rev-parse HEAD)
  git log "$MB..HEAD" --format='- %h %s' > "$TMP/commits.txt"
  git diff --stat "$MB...HEAD" > "$TMP/diffstat.txt"
  ticket_block "$id"
  owner=$(field "$id" owner)
  title=$(field "$id" title)
  submitted=$(git log -1 --format=%cs HEAD)

  mkdir -p prs
  cp prs/TEMPLATE.md "prs/$id.md"
  f="prs/$id.md"
  fill_line "$f" "{{ID}}" "$id"
  fill_line "$f" "{{TITLE}}" "$title"
  fill_line "$f" "{{OWNER}}" "$owner"
  fill_line "$f" "{{BRANCH}}" "ticket/$id"
  fill_line "$f" "{{BASE}}" "$base ($MB)"
  fill_line "$f" "{{HEAD}}" "$head"
  fill_line "$f" "{{SUBMITTED}}" "$submitted"
  fill_line "$f" "{{VERDICT}}" "pending"
  fill_line "$f" "{{REVIEWER}}" "-"
  fill_line "$f" "{{REVIEWED}}" "-"
  fill_line "$f" "{{MERGE_COMMIT}}" "-"
  fill_block "$f" "{{COMMITS}}" "$TMP/commits.txt"
  fill_block "$f" "{{DIFFSTAT}}" "$TMP/diffstat.txt"
  fill_block "$f" "{{CHECKS}}" "$TMP/checks.txt"
  fill_block "$f" "{{ACCEPTANCE}}" "$TMP/acceptance.txt"
  fill_block "$f" "{{RISKS}}" "$TMP/risks.txt"
  fill_line "$f" "{{FINDINGS}}" "pending steward review (sh tools/pr.sh review $id)"
  fill_line "$f" "{{VERDICT_TEXT}}" "Pending — steward runs: sh tools/pr.sh review $id --approve|--request-changes REASON"
  fill_line "$f" "{{MERGE_TEXT}}" "(pending — filled by sh tools/pr.sh merge $id)"

  # ticket -> review (metadata via the tool), commit PR record + metadata on the branch
  $TICKETS state "$id" review || die "could not set $id to review"
  git add "prs/$id.md" tickets/
  vibe_commit "ticket($id): submit PR prs/$id.md"

  git push review "ticket/$id"
  echo
  echo "PR record: prs/$id.md"
  echo "pushed ticket/$id to remote 'review'"
  echo "next (steward, on main): sh tools/pr.sh review $id --approve   # or --request-changes 'reason'"
  echo "                        sh tools/pr.sh list"
}

cmd_review() {
  [ $# -ge 1 ] || { usage >&2; die "review needs a ticket id"; }
  id=$1; shift
  verdict=; reason=
  while [ $# -gt 0 ]; do
    case "$1" in
      --approve) verdict=approved; shift ;;
      --request-changes) [ $# -ge 2 ] || die "--request-changes needs a REASON"; verdict=changes-requested; reason=$2; shift 2 ;;
      *) die "unexpected argument: $1" ;;
    esac
  done
  if [ -z "$verdict" ]; then
    verdict=changes-requested
    reason="no verdict flag given; pr.sh review defaults to changes-requested — pass --approve to approve"
  fi
  require_steward "$id" review
  require_main_worktree
  require_clean
  MB=$(main_branch)
  state=$(field "$id" state) || die "no ticket $id"
  [ "$state" = "review" ] || [ "$state" = "doing" ] || die "$id is '$state', expected review (submit sets it)"
  git remote get-url review >/dev/null 2>&1 || die "no 'review' remote; run sh tools/setup-review-remote.sh"
  git fetch review
  branch="ticket/$id"
  ref=$branch
  git show-ref --verify --quiet "refs/heads/$branch" || ref="review/$branch"
  wt=".worktrees/$id"
  [ -d "$ROOT/$wt" ] || die "worktree $wt missing; cannot run checks there (recover: python3 tools/tickets.py recover)"

  echo "== review $id: diff $MB...$ref =="
  git diff --stat "$MB...$ref" | sed 's/^/  /'
  echo "-- full diff --"
  git diff "$MB...$ref"

  if ! run_checks "$ROOT/$wt"; then
    cat "$TMP/checks.txt"
    die "tools/check.sh failed in $wt; review aborted"
  fi
  protected=$(git diff "$MB...$ref" -- BRIEF.md docs/discovery docs/reviews | wc -l | tr -d ' ')
  # R04: real glob/dir matching against the ticket touches (fnmatch + dir prefixes,
  # 'new:' declared paths) — replaces the old literal `grep -F` filter.
  if touch_out=$($TICKETS check-touches "$id" --diff "$MB...$ref" 2>&1); then
    touches_ok=0
  else
    touches_ok=1
    if [ "$verdict" = approved ]; then
      die "cannot approve: diff $MB...$ref touches files outside the ticket touches:
$touch_out
Use --request-changes instead; the worker must narrow the diff or extend touches via tools/tickets.py."
    fi
  fi

  base=$(git merge-base "$MB" "$ref" 2>/dev/null || git rev-parse "$MB")
  head=$(git rev-parse "$ref")
  git log "$MB..$ref" --format='- %h %s' > "$TMP/commits.txt" 2>/dev/null || echo "(no commits)" > "$TMP/commits.txt"
  git diff --stat "$MB...$ref" > "$TMP/diffstat.txt"
  ticket_block "$id"
  owner=$(field "$id" owner)
  title=$(field "$id" title)
  reviewer=$(git config user.name 2>/dev/null || echo "${USER:-unknown}")
  today=$(date +%F)

  {
    echo "diffstat $MB...$ref:"; cat "$TMP/diffstat.txt"; echo
    echo "protected files (BRIEF.md, docs/discovery/, docs/reviews/) changed lines: $protected (must be 0)"
    if [ "$touches_ok" = 0 ]; then
      echo "files outside the ticket touches: 0 (must be 0) — $touch_out"
    else
      echo "files outside the ticket touches: VIOLATION (must be 0):"
      printf '%s\n' "$touch_out" | sed 's/^/  /'
    fi
    echo "checks:"; cat "$TMP/checks.txt"
  } > "$TMP/findings.txt"

  mkdir -p prs
  cp prs/TEMPLATE.md "prs/$id.review.md"
  f="prs/$id.review.md"
  fill_line "$f" "{{ID}}" "$id"
  fill_line "$f" "{{TITLE}}" "$title"
  fill_line "$f" "{{OWNER}}" "$owner"
  fill_line "$f" "{{BRANCH}}" "$branch"
  fill_line "$f" "{{BASE}}" "$base ($MB)"
  fill_line "$f" "{{HEAD}}" "$head"
  fill_line "$f" "{{SUBMITTED}}" "see prs/$id.md"
  fill_line "$f" "{{VERDICT}}" "$verdict"
  fill_line "$f" "{{REVIEWER}}" "$reviewer"
  fill_line "$f" "{{REVIEWED}}" "$today"
  fill_line "$f" "{{MERGE_COMMIT}}" "-"
  fill_block "$f" "{{COMMITS}}" "$TMP/commits.txt"
  fill_block "$f" "{{DIFFSTAT}}" "$TMP/diffstat.txt"
  fill_block "$f" "{{CHECKS}}" "$TMP/checks.txt"
  fill_block "$f" "{{ACCEPTANCE}}" "$TMP/acceptance.txt"
  fill_block "$f" "{{RISKS}}" "$TMP/risks.txt"
  fill_block "$f" "{{FINDINGS}}" "$TMP/findings.txt"
  if [ "$verdict" = approved ]; then
    fill_line "$f" "{{VERDICT_TEXT}}" "APPROVED by $reviewer on $today. Merge with: sh tools/pr.sh merge $id"
  else
    fill_line "$f" "{{VERDICT_TEXT}}" "CHANGES REQUESTED by $reviewer on $today: $reason"
  fi
  fill_line "$f" "{{MERGE_TEXT}}" "(not merged)"

  git add "prs/$id.review.md"
  vibe_commit "ticket($id): review verdict: $verdict (coordination commit)"
  echo
  echo "verdict: $verdict -> prs/$id.review.md (committed on $MB)"
  if [ "$verdict" = approved ]; then
    echo "next: sh tools/pr.sh merge $id"
  else
    echo "worker: fix and resubmit; hand the ticket back with: python3 tools/tickets.py state $id doing --owner $owner"
  fi
}

cmd_merge() {
  [ $# -ge 1 ] || { usage >&2; die "merge needs a ticket id"; }
  id=$1
  require_steward "$id" merge
  require_main_worktree
  require_clean
  MB=$(main_branch)
  branch="ticket/$id"
  wt=".worktrees/$id"

  [ -f "prs/$id.review.md" ] || die "no review record prs/$id.review.md; run: sh tools/pr.sh review $id --approve"
  grep -q '"verdict": "approved"' "prs/$id.review.md" || die "review verdict in prs/$id.review.md is not approved; refusing to merge"
  git show-ref --verify --quiet "refs/heads/$branch" || die "branch $branch missing (recover: python3 tools/tickets.py recover)"
  [ -d "$ROOT/$wt" ] || die "worktree $wt missing; refusing to merge without acceptance run"

  echo "== merge $id: rebase $branch onto $MB in $wt =="
  if ! git -C "$ROOT/$wt" rebase "$MB"; then
    die "rebase conflict — worktree left intact at $wt; resolve there, then re-run: sh tools/pr.sh merge $id"
  fi
  if ! run_checks "$ROOT/$wt"; then
    cat "$TMP/checks.txt"
    die "tools/check.sh failed after rebase; merge aborted, worktree left intact at $wt"
  fi
  echo "checks after rebase: PASS"
  echo "checks after rebase: PASS"

  # R08: build the message in a variable; git merge takes -m, not -F -
  msg=$(printf 'Merge ticket/%s (PR prs/%s.md) into %s\n\nticket(%s) merged via prs/%s.md; review approved in prs/%s.review.md.\n\nGenerated by Mistral Vibe.\nCo-Authored-By: Mistral Vibe <vibe@mistral.ai>\n' \
    "$id" "$id" "$MB" "$id" "$id" "$id")
  git merge --no-ff "$branch" -m "$msg"
  mc=$(git rev-parse HEAD)
  echo "merged as $mc"

  # ticket done on main (board), clear linkage fields, commit the board
  $TICKETS state "$id" done || die "could not set $id done"
  $TICKETS assign "$id" --clear
  # record merge + verdict in the PR record (it arrived on main via the merge)
  if [ -f "prs/$id.md" ]; then
    sed -i "s/\"verdict\": \"pending\"/\"verdict\": \"approved\"/; s/\"merge_commit\": \"-\"/\"merge_commit\": \"$mc\"/" "prs/$id.md"
    printf '\n## Merge\n\n- merge commit: %s\n- verdict: approved (prs/%s.review.md)\n- merged by: sh tools/pr.sh merge %s\n' "$mc" "$id" "$id" >> "prs/$id.md"
  fi
  git add tickets/ "prs/$id.md"
  if ! git diff --cached --quiet; then
    vibe_commit "ticket($id): mark $id done, record merge $mc (coordination commit)"
  fi

  # cleanup: worktree, branch locally and on review, push main
  git worktree remove "$ROOT/$wt" || die "could not remove $wt after merge; inspect manually"
  git worktree prune
  echo "removed worktree $wt"
  git branch -d "$branch" 2>/dev/null || git branch -D "$branch"
  echo "deleted local branch $branch"
  if git remote get-url review >/dev/null 2>&1; then
    git push review --delete "$branch" 2>/dev/null && echo "deleted review/$branch"
  fi
  git push review "$MB"
  # R01: verify the push actually landed on the review remote; fail loudly if not
  push_main_to_review "$MB"

  echo
  echo "ok: $id merged ($mc), state done, worktree+branch removed"
  echo "verify: git log --oneline $MB | head -3 ; python3 tools/tickets.py field $id state"
}

cmd_list() {
  MB=$(main_branch); [ -n "$MB" ] || MB=main
  echo "open PRs (tickets in review state):"
  # R09: parse the JSON output of tickets.py list, not the human table
  ids=$($TICKETS list --state review --json true 2>/dev/null | python3 -c '
import json, sys
for t in json.load(sys.stdin):
    print(t["id"])
')
  found=0
  for id in $ids; do
    found=1
    owner=$(field "$id" owner)
    branch=$(field "$id" branch)
    verdict="-"
    if [ -f "prs/$id.review.md" ]; then
      verdict=$(sed -n 's/.*"verdict": "\([^"]*\)".*/\1/p' "prs/$id.review.md" | head -n 1)
    fi
    ab=$(git rev-list --left-right --count "$MB...$branch" 2>/dev/null | tr '\t' '/' || echo "?")
    printf '  %s  owner=%s  branch=%s  verdict=%s  main<branch ahead/behind=%s\n' "$id" "$owner" "$branch" "$verdict" "$ab"
  done
  [ "$found" = 1 ] || echo "  (none)"
  echo
  echo "in flight: sh tools/wt.sh list"
}

case "${1:-}" in
  submit) shift; cmd_submit "$@" ;;
  review) shift; cmd_review "$@" ;;
  merge) shift; cmd_merge "$@" ;;
  list) cmd_list ;;
  -h|--help|help|"") usage ;;
  *) usage >&2; die "unknown command: $1" ;;
esac
