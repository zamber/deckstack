#!/bin/sh
# deckstack worktree lifecycle — owns .worktrees/<id> + branch ticket/<id>.
#   sh tools/wt.sh new <DS-XXX> [--owner NAME]   (run from the MAIN worktree)
#   sh tools/wt.sh list
#   sh tools/wt.sh remove <DS-XXX>               (only done/abandoned tickets)
# Ticket metadata is owned by tools/tickets.py — this script only calls it.
# See AGENTS.md and docs/AGENT-WORKFLOW.md.
set -eu
ROOT=$(CDPATH= cd -- "$(dirname -- "$0")/.." && pwd)
cd "$ROOT"
TICKETS="python3 $ROOT/tools/tickets.py"

die() { echo "wt.sh: error: $*" >&2; exit 1; }
usage() {
  cat <<'EOF'
usage:
  sh tools/wt.sh new <DS-XXX> [--owner NAME]   claim + create .worktrees/<DS-XXX> on branch ticket/<DS-XXX> from main
  sh tools/wt.sh list                           worktrees vs board in-flight tickets
  sh tools/wt.sh remove <DS-XXX>                cleanup for done/abandoned tickets (worktree, branch, metadata)
EOF
}

main_branch() {
  if git show-ref --verify --quiet refs/heads/main; then echo main
  elif git show-ref --verify --quiet refs/heads/master; then echo master
  else echo ""; fi
}

require_main_worktree() {
  [ -d "$ROOT/.git" ] || die "run from the MAIN worktree ($ROOT), not from a linked worktree"
  MB=$(main_branch)
  [ -n "$MB" ] || die "no main/master branch found"
  [ "$(git symbolic-ref --short HEAD)" = "$MB" ] || die "main worktree must be on branch $MB"
}

require_clean() {
  [ -z "$(git status --porcelain)" ] || die "working tree is dirty; commit or stash first (ignored files are fine)"
}

# R08: message via stdin (git commit -F -) — no here-doc delimiter to break.
vibe_commit() { # $1 = commit message (subject + body)
  printf '%s\n\nGenerated by Mistral Vibe.\nCo-Authored-By: Mistral Vibe <vibe@mistral.ai>\n' "$1" | git commit -F -
}

field() { $TICKETS field "$1" "$2" 2>/dev/null; }

cmd_new() {
  id=; owner=
  while [ $# -gt 0 ]; do
    case "$1" in
      --owner) [ $# -ge 2 ] || die "--owner needs a value"; owner=$2; shift 2 ;;
      -h|--help) usage; exit 0 ;;
      *) if [ -z "$id" ]; then id=$1; shift; else die "unexpected argument: $1"; fi ;;
    esac
  done
  [ -n "$id" ] || { usage >&2; die "new needs a ticket id"; }
  require_main_worktree
  require_clean
  MB=$(main_branch)

  state=$(field "$id" state) || die "no ticket $id"
  [ "$state" = "ready" ] || die "$id is '$state'; only a ready ticket (deps done) can be started"
  deps=$(field "$id" depends_on | tr -d '[]"' | tr ',' ' ')
  for dep in $deps; do
    dst=$(field "$dep" state) || die "unknown dep $dep"
    [ "$dst" = "done" ] || die "dep $dep of $id is '$dst', not done"
  done
  [ -n "$owner" ] || owner=$(git config user.name 2>/dev/null || echo agent)

  # claim (tickets.py refuses on doing-ticket touch collisions before writing)
  $TICKETS claim "$id" --owner "$owner" || die "claim of $id failed (state/deps/collision)"

  # coordination commit on main: ONLY the ticket metadata the claim touched
  git add tickets/
  if ! git diff --cached --quiet; then
    vibe_commit "ticket($id): claim $id for $owner (coordination commit)"
  fi

  wt=".worktrees/$id"
  if [ -e "$wt" ] || git worktree list --porcelain | grep -q "worktree $ROOT/$wt\$"; then
    die "worktree $wt already exists"
  fi
  if git show-ref --verify --quiet "refs/heads/ticket/$id"; then
    die "branch ticket/$id already exists"
  fi
  git worktree add "$wt" -b "ticket/$id" "$MB"

  echo
  echo "created worktree $wt on branch ticket/$id (from $MB @ $(git rev-parse --short $MB))"
  echo "ticket $id is now doing, owner $owner"
  echo
  echo "next commands:"
  cat <<EOF
  cd $ROOT/$wt
  # edit ONLY the paths in $id's touches, then:
  git add -A
  git commit -m "ticket($id): <subject>" -m "Generated by Mistral Vibe." -m "Co-Authored-By: Mistral Vibe <vibe@mistral.ai>"
  sh tools/pr.sh submit $id          # writes prs/$id.md, pushes ticket/$id to review
EOF
}

cmd_list() {
  MB=$(main_branch)
  echo "main worktree: $ROOT (branch $(git symbolic-ref --short HEAD), base $MB)"
  echo
  echo "git worktrees:"
  git worktree list | sed 's/^/  /'
  echo
  echo "board in flight:"
  found=0
  for st in doing review; do
    for id in $($TICKETS list --state "$st" 2>/dev/null | awk '/^DS-/ {print $1}'); do
      found=1
      printf '  %s state=%s owner=%s branch=%s worktree=%s pr=%s\n' \
        "$id" "$st" "$(field "$id" owner)" "$(field "$id" branch)" "$(field "$id" worktree)" "$(field "$id" pr)"
    done
  done
  [ "$found" = 1 ] || echo "  (none)"
  echo
  echo "open PRs: sh tools/pr.sh list"
}

cmd_remove() {
  [ $# -ge 1 ] || { usage >&2; die "remove needs a ticket id"; }
  id=$1
  require_main_worktree
  require_clean
  state=$(field "$id" state) || die "no ticket $id"
  case "$state" in
    done|blocked) ;;
    *) die "$id is '$state'; remove is only for done (merged) or blocked (abandoned) tickets" ;;
  esac
  branch=$(field "$id" branch); [ "$branch" = "null" ] && branch=
  wt=$(field "$id" worktree); [ "$wt" = "null" ] && wt=

  if [ -n "$wt" ] && [ -d "$ROOT/$wt" ]; then
    git worktree remove "$ROOT/$wt" || die "could not remove $wt (dirty or locked?); inspect manually"
    git worktree prune
    echo "removed worktree $wt"
  else
    echo "no worktree $wt present"
  fi

  if [ -n "$branch" ] && git show-ref --verify --quiet "refs/heads/$branch"; then
    case "$state" in
      done)    git branch -d "$branch" 2>/dev/null || git branch -D "$branch" ;;
      blocked) git branch -D "$branch" ;;
    esac
    echo "deleted local branch $branch"
  else
    echo "no local branch ${branch:-<none>} present"
  fi

  if [ -n "$branch" ] && git remote get-url review >/dev/null 2>&1; then
    if git push review --delete "$branch" 2>/dev/null; then
      echo "deleted review/$branch"
    else
      echo "no review/$branch to delete"
    fi
  fi

  $TICKETS assign "$id" --clear
  git add tickets/
  if ! git diff --cached --quiet; then
    vibe_commit "ticket($id): clear worktree/branch metadata after $state (coordination commit)"
  fi
  echo "ok: $id is $state, branch/worktree metadata cleared"
}

case "${1:-}" in
  new) shift; cmd_new "$@" ;;
  list) cmd_list ;;
  remove) shift; cmd_remove "$@" ;;
  -h|--help|help|"") usage ;;
  *) usage >&2; die "unknown command: $1" ;;
esac
