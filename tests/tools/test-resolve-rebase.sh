#!/bin/sh
# tests/tools/test-resolve-rebase.sh — self-contained regression test for
# tools/resolve-rebase.sh. Builds throwaway git repos in $(mktemp -d); no network,
# no assumptions about the main repo.
#
#   Case A: whitelisted conflicts (tickets/BOARD.md, tickets/DS-901.md, Cargo.lock)
#           -> resolver exits 0, files equal main's versions, Cargo.lock regenerated
#              by cargo, rebase finished.
#   Case B: same plus a README.md conflict (outside the whitelist)
#           -> resolver exits nonzero, prints README.md, rebase still in progress
#              with README.md unmerged.
#   Case C: no rebase in progress -> resolver exits 2.
#
# Prints RESOLVE-REBASE: ALL PASSED and exits 0 on success.
set -u
ROOT=$(CDPATH= cd -- "$(dirname -- "$0")/../.." && pwd)
RESOLVER="$ROOT/tools/resolve-rebase.sh"
[ -f "$RESOLVER" ] || { echo "test-resolve-rebase: FAIL: missing $RESOLVER" >&2; exit 1; }

TMP=$(mktemp -d) || { echo "test-resolve-rebase: FAIL: mktemp -d" >&2; exit 1; }
trap 'rm -rf "$TMP"' EXIT

fail() { echo "test-resolve-rebase: FAIL: $*" >&2; exit 1; }
ok()   { echo "test-resolve-rebase: ok: $*"; }

have_cargo=0
if command -v cargo >/dev/null 2>&1; then have_cargo=1; else
  echo "test-resolve-rebase: SKIP: cargo not in PATH — Cargo.lock assertions skipped"
fi

rebase_open() { # rebase_open <repo>
  r=$1
  for d in rebase-merge rebase-apply; do
    p=$(git -C "$r" rev-parse --git-path "$d")
    case "$p" in /*) ;; *) p="$r/$p" ;; esac
    [ -d "$p" ] && return 0
  done
  return 1
}

# setup_repo <dir> <with-readme>: base commit on main with the conflict-able files
setup_repo() {
  d=$1; wr=$2
  git init -q -b main "$d" || fail "git init $d"
  git -C "$d" config user.email test@example.com
  git -C "$d" config user.name test
  mkdir -p "$d/tickets"
  printf 'board base\n' > "$d/tickets/BOARD.md"
  printf 'ds901 base\n' > "$d/tickets/DS-901.md"
  printf '[package]\nname = "resolve-rebase-test"\nversion = "0.1.0"\nedition = "2021"\n' > "$d/Cargo.toml"
  mkdir -p "$d/src"
  printf 'fn main() {}\n' > "$d/src/main.rs"
  if [ "$have_cargo" -eq 1 ]; then
    (cd "$d" && cargo generate-lockfile --offline >/dev/null 2>&1) || fail "cargo generate-lockfile (base) in $d"
    printf '# base lock marker\n' >> "$d/Cargo.lock"
  else
    printf '# fake lock base\n' > "$d/Cargo.lock"
  fi
  [ "$wr" = 1 ] && printf 'readme base\n' > "$d/README.md"
  git -C "$d" add -A
  git -C "$d" commit -q -m base || fail "base commit in $d"
}

# diverge <dir> <tag> <with-readme>: feature and main both change the same files
diverge() {
  d=$1; tag=$2; wr=$3
  git -C "$d" checkout -q -b feature
  printf 'board %s\n' "$tag" > "$d/tickets/BOARD.md"
  printf 'ds901 %s\n' "$tag" > "$d/tickets/DS-901.md"
  if [ "$have_cargo" -eq 1 ]; then
    printf '# %s lock marker\n' "$tag" >> "$d/Cargo.lock"
  else
    printf '# %s lock\n' "$tag" >> "$d/Cargo.lock"
  fi
  [ "$wr" = 1 ] && printf 'readme %s\n' "$tag" > "$d/README.md"
  git -C "$d" add -A
  git -C "$d" commit -q -m "feature $tag" || fail "feature commit in $d"
  git -C "$d" checkout -q main
  printf 'board main-%s\n' "$tag" > "$d/tickets/BOARD.md"
  printf 'ds901 main-%s\n' "$tag" > "$d/tickets/DS-901.md"
  if [ "$have_cargo" -eq 1 ]; then
    printf '# main-%s lock marker\n' "$tag" >> "$d/Cargo.lock"
  else
    printf '# main-%s lock\n' "$tag" >> "$d/Cargo.lock"
  fi
  [ "$wr" = 1 ] && printf 'readme main-%s\n' "$tag" > "$d/README.md"
  git -C "$d" add -A
  git -C "$d" commit -q -m "main $tag" || fail "main commit in $d"
  git -C "$d" checkout -q feature
}

# ---------- Case A: whitelisted conflicts resolve automatically ----------
A="$TMP/a"
setup_repo "$A" 0
diverge "$A" a 0
git -C "$A" rebase main >/dev/null 2>&1 && fail "case A: rebase unexpectedly clean"
rebase_open "$A" || fail "case A: rebase not in progress after conflict"

sh "$RESOLVER" "$A" > "$TMP/a.log" 2>&1
rc=$?
[ "$rc" -eq 0 ] || { cat "$TMP/a.log" >&2; fail "case A: resolver exit $rc, expected 0"; }
ok "case A: resolver exited 0"

[ -z "$(git -C "$A" diff --name-only --diff-filter=U)" ] || fail "case A: unmerged paths remain"
[ "$(cat "$A/tickets/BOARD.md")" = "board main-a" ] || fail "case A: tickets/BOARD.md is not main's version ($(cat "$A/tickets/BOARD.md"))"
[ "$(cat "$A/tickets/DS-901.md")" = "ds901 main-a" ] || fail "case A: tickets/DS-901.md is not main's version ($(cat "$A/tickets/DS-901.md"))"
ok "case A: BOARD.md and DS-901.md equal main's versions (--ours = main)"

rebase_open "$A" && fail "case A: rebase still in progress after resolver"
ok "case A: rebase finished"

if [ "$have_cargo" -eq 1 ]; then
  git -C "$A" show main:Cargo.lock | grep -q 'main-a lock marker' || fail "case A: sanity — main:Cargo.lock lost its marker"
  if grep -q 'lock marker' "$A/Cargo.lock"; then
    fail "case A: Cargo.lock still contains a branch marker (not regenerated by cargo)"
  fi
  (cd "$A" && cargo generate-lockfile --offline >/dev/null 2>&1) || fail "case A: cargo generate-lockfile after resolver"
  [ -z "$(git -C "$A" status --porcelain -- Cargo.lock)" ] || fail "case A: Cargo.lock differs from cargo generate-lockfile output (not regenerated)"
  ok "case A: Cargo.lock regenerated by cargo (matches generate-lockfile output)"
else
  echo "test-resolve-rebase: SKIP: case A Cargo.lock regeneration assertions (no cargo)"
fi

# ---------- Case B: conflict outside the whitelist stays manual ----------
B="$TMP/b"
setup_repo "$B" 1
diverge "$B" b 1
git -C "$B" rebase main >/dev/null 2>&1 && fail "case B: rebase unexpectedly clean"

out=$(sh "$RESOLVER" "$B" 2>&1); rc=$?
[ "$rc" -ne 0 ] || fail "case B: resolver exit 0, expected nonzero"
printf '%s\n' "$out" | grep -q 'README.md' || { printf '%s\n' "$out" >&2; fail "case B: resolver output does not name README.md"; }
rebase_open "$B" || fail "case B: rebase not still in progress after resolver refused"
git -C "$B" diff --name-only --diff-filter=U | grep -q '^README.md$' || fail "case B: README.md not unmerged after resolver refused"
ok "case B: resolver exited $rc, printed README.md, rebase left in progress with README.md unmerged"

# ---------- Case C: no rebase in progress -> exit 2 ----------
C="$TMP/c"
setup_repo "$C" 0
sh "$RESOLVER" "$C" >/dev/null 2>&1
rc=$?
[ "$rc" -eq 2 ] || fail "case C: resolver exit $rc, expected 2 (no rebase in progress)"
ok "case C: resolver exits 2 when no rebase is in progress"

echo "RESOLVE-REBASE: ALL PASSED"
exit 0
