#!/usr/bin/env python3
"""deckstack PLUGIN-ABUSE conformance suite (ticket DS-053, tests/conformance/plugins/).

Machine-checked proof (on the REAL binaries, black-box, over ds-vdev) that a hostile
or buggy plugin cannot take down the daemon, escape its capabilities, or reach
non-granted hosts — the phase-5 "abuse tests pass" exit. Threat rows T3/T5/T6/T11 of
docs/20-security.md (the Test column of the table points here).

Each case boots a fresh ds-vdev + ds-daemon on a temp dir with its own
XDG_DATA_HOME, installs small raw-stdio fixture plugins (generated by the test,
stdlib only — see plugins_harness.py), drives them ONLY through the real `ds` binary and
the raw NDJSON control socket (`ds bind app/abuse/<case> --do 'plugin <id>.go'` +
IPC `emit`), and asserts:

  010 fork bomb: contained by the nproc rlimit (forks_ok <= grant), the plugin is
      killed (CPU rlimit), daemon healthy, /plugins shows the failure, no leaked pid
  020 memory bomb: the AS rlimit kills the plugin (MemoryError), host healthy,
      daemon RSS bounded, crash visible in /plugins + daemon.log
  030 capability violation: set/get effects without the grant -> E_CAP, counted in
      /plugins/<id>/stats.violations, no state change; the granted emit cap still works
  040 filesystem traversal: fs request outside fs_roots / set effect outside the
      writable subset -> E_CAP, nothing read (direct read denied under Landlock),
      granted root still readable
  050 oversized net URL (> 2048 B) -> E_LIMIT, non-http URL -> E_SCHEMA, invalid
      net:<glob> in the manifest -> refused at manifest validation (E_SCHEMA at
      install; the invoke is refused E_CAP and /plugins has no entry)
  060 invoke timeout 2 s -> E_LIMIT binding-error, plugin degraded, remaining
      binding steps still run; second consecutive timeout -> restart with a new pid
  070 net glob edges (M5/S4) exactly: `*.lan` matches lights.lan but NOT lan,
      a.b.lan, lights.lan.evil.com; `lights.lan` matches only lights.lan; the
      allowed host succeeds end-to-end via a fake 127.0.0.1 lights server; a raw
      socket from the plugin itself is denied (Landlock ABI>=4)
  080 crash -> E_DEVICE mid-call, watchdog respawns (stats.restarts) and after 3
      respawns within 600 s disables the plugin (stopped + disabled_reason)

Every case: bounded runtime (every wait has a timeout), cleanup in tearDown (daemon
stopped, plugin processes swept and asserted gone, temp dir removed), clear PASS/FAIL
lines. The suite exits 0 only with all cases contained.

Usage:
    python3 tests/conformance/plugins/run.py [--verbose] [-k SUBSTR]
    python3 tests/conformance/run.py            # runs this suite too (registered there)
    python3 tests/conformance/run.py -k plugins # only these cases

Exit code 0 = all green, nonzero = at least one failure. A hang is a finding, not a
retry: the whole run is bounded by a watchdog alarm.
"""

