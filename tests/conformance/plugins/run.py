def rss_kb(pid):
    try:
        with open("/proc/%d/status" % pid) as f:
            for line in f:
                if line.startswith("VmRSS:"):
                    return int(line.split()[1])
    except OSError:
        pass
    return 0


def landlock_enforced(plugin_value):
    """True when the plugin's own landlock status line says the sandbox restricted
    (the 'unavailable' branch is the documented gap, docs/20-security.md T11)."""
    ll = (plugin_value.get("state") or {}).get("landlock") or ""
    return bool(ll) and "unavailable" not in ll


class PluginAbuse(unittest.TestCase):
    """One fresh stack (vdev + daemon + fixtures) per case — full isolation."""

    def setUp(self):
        self.bins = ensure_binaries()
        self.stack = None
        self.ipc = None
        self.fake = None

    def tearDown(self):
        try:
            if self.ipc is not None:
                self.ipc.close()
        except Exception:
            pass
        if self.fake is not None:
            self.fake.stop()
            self.fake = None
        if self.stack is not None:
            problems = self.stack.stop()
            self.assertEqual(problems, [],
                             "cleanup problems (leaked plugin processes?): %s" % problems)
            self.stack = None

    # ---- helpers -----------------------------------------------------------

    def boot(self, plugins):
        """plugins: list of (manifest, behavior, extra_files). Boots vdev+daemon and
        opens an authenticated control connection subscribed to /deck/system/* and
        /plugin/*."""
        st = Stack(self.bins)
        for manifest, behavior, extra in plugins:
            install_plugin(st.xdg, manifest, behavior, extra)
        st.start()
        self.stack = st
        c = st.ipc().hello_auth(st.token)
        c.subscribe("/deck/system/*")
        c.subscribe("/plugin/*")
        self.ipc = c
        return st

    def kick(self, st, pid, topic, action="go"):
        """Bind the topic to `plugin <pid>.<action>`, emit once to boot the plugin
        host (that first invoke is refused E_DEVICE while the handshake runs — the
        hostile behavior only fires on the second, real emit), and wait until the
        plugin reports status=running."""
        st.bind(topic, "plugin %s.%s" % (pid, action))
        st.emit(self.ipc, topic)
        st.drain_events(self.ipc, 1.0)
        return st.wait_plugin(pid, "running")

    def wait_probe(self, st, pid, n, timeout=45):
        """Wait until /plugins/<pid>/state/probe carries >= n recorded probe replies."""
        deadline = time.monotonic() + timeout
        last = None
        while time.monotonic() < deadline:
            v = st.try_get_value("/plugins/%s/state/probe" % pid)
            last = v
            if isinstance(v, list) and len(v) >= n:
                return v
            time.sleep(0.15)
        raise AssertionError(
            "plugin %s probe did not reach %d entries within %ss (last: %r; log: %s)"
            % (pid, n, timeout, last, st.read_log(2500))
        )

    def wait_event(self, topic, timeout=10):
        deadline = time.monotonic() + timeout
        while time.monotonic() < deadline:
            try:
                ev = self.ipc.next_event(timeout=max(0.2, deadline - time.monotonic()))
            except socket.timeout:
                break
            if ev.get("topic") == topic:
                return ev
        raise AssertionError("no event on topic %s within %ss" % (topic, timeout))

    # ---- 010 fork bomb (T3) -------------------------------------------------

    def test_plugins_010_forkbomb_contained_by_nproc(self):
        st = self.boot([(
            make_manifest("forkbomb", ["state.write"],
                          resources={"cpu_s": 3, "nproc": 64, "nofile": 64, "as_mb": 1024}),
            {"mode": "forkbomb", "tag": "FORKBOMB"},
            None,
        )])
        topic = "app/abuse/forkbomb"
        v = self.kick(st, "forkbomb", topic)
        pid0 = v["state"]["pid"]
        baseline = uid_proc_count()
        st.emit(self.ipc, topic)  # the bomb fires on this invoke and never replies
        err = st.wait_binding_error(self.ipc, 15)
        self.assertIn(err["error"]["code"], ("E_LIMIT", "E_DEVICE"),
                      "invoke must time out (E_LIMIT) or fail on the crash (E_DEVICE): %s" % err)
        # the rlimits kill the plugin: crash + watchdog respawn, old pid gone
        v = st.wait_plugin_pred(
            "forkbomb", lambda v: v["stats"]["restarts"] >= 1,
            timeout=60, what="crash+respawn after the rlimit kill")
        self.assertTrue(st.pid_gone(pid0),
                        "the bombed plugin pid %s is still alive" % pid0)
        now = uid_proc_count()
        self.assertLessEqual(now, baseline + 8,
                             "process count grew unboundedly: %d -> %d" % (baseline, now))
        logtxt = st.read_log(30000)
        self.assertIn("FORKBOMB", logtxt, "the bomb's own log line must be in the daemon log")
        m = re.search(r"FORKBOMB forks_ok=(\d+) fork_errors=(\d+)", logtxt)
        self.assertIsNotNone(m, "FORKBOMB summary line missing:\n%s" % logtxt[-3000:])
        self.assertLessEqual(int(m.group(1)), 64,
                             "plugin forked %s children beyond its nproc=64 grant" % m.group(1))
        # daemon healthy afterwards and still functional
        self.assertTrue(st.daemon_alive(self.ipc), "daemon died after the fork bomb")
        st.set_json("/controls/keys/8/label", "alive")
        self.assertEqual(st.try_get_value("/controls/keys/8/label"), "alive")
        v = st.plugin_state("forkbomb")
        self.assertGreaterEqual(v["stats"]["restarts"], 1)
        self.assertTrue(v["state"].get("last_error"), v["state"])

    # ---- 020 memory bomb (T3) ----------------------------------------------

    def test_plugins_020_memory_bomb_killed_by_as_limit(self):
        st = self.boot([(
            make_manifest("membomb", ["state.write"],
                          resources={"cpu_s": 10, "nproc": 64, "nofile": 64, "as_mb": 256}),
            {"mode": "membomb", "tag": "MEMBOMB", "chunk_mb": 16},
            None,
        )])
        topic = "app/abuse/membomb"
        v = self.kick(st, "membomb", topic)
        pid0 = v["state"]["pid"]
        rss0 = rss_kb(st.daemon_pid)
        st.emit(self.ipc, topic)  # allocate until the AS limit kills the plugin
        err = st.wait_binding_error(self.ipc, 15)
        self.assertIn(err["error"]["code"], ("E_LIMIT", "E_DEVICE"), err)
        v = st.wait_plugin_pred(
            "membomb", lambda v: v["stats"]["restarts"] >= 1,
            timeout=60, what="crash+respawn after the AS kill")
        self.assertTrue(st.pid_gone(pid0),
                        "the memory-bombed plugin pid %s is still alive" % pid0)
        logtxt = st.read_log(30000)
        self.assertIn("MEMBOMB allocated_mb=", logtxt,
                      "the AS-limit kill must be visible in the daemon log:\n%s"
                      % logtxt[-3000:])
        # the host stayed healthy and its own memory bounded (the bomb died in the child)
        self.assertTrue(st.daemon_alive(self.ipc), "daemon died after the memory bomb")
        rss1 = rss_kb(st.daemon_pid)
        self.assertLess(rss1, rss0 + 200 * 1024,
                        "daemon RSS grew by %d kB (bomb leaked into the host?)"
                        % (rss1 - rss0))
        v = st.plugin_state("membomb")
        self.assertGreaterEqual(v["stats"]["restarts"], 1)
        self.assertTrue(v["state"].get("last_error"), v["state"])

    # ---- 030 capability violation (T3) --------------------------------------

    def test_plugins_030_capability_violation_E_CAP_no_state_change(self):
        # caps deliberately omit state.write and state.read; only emit is granted
        st = self.boot([(
            make_manifest("capvio", ["emit"]),
            {"mode": "capvio", "tag": "CAPVIO"},
            None,
        )])
        topic = "app/abuse/capvio"
        self.kick(st, "capvio", topic)
        policy0 = st.try_get_value("/policy/net/allow_hosts")
        st.emit(self.ipc, topic)
        v = st.wait_plugin_pred(
            "capvio", lambda v: v["stats"]["violations"] >= 3,
            timeout=20, what="violations counted (get without state.read + 2 set effects)")
        self.assertEqual(v["stats"]["violations"], 3, v["stats"])
        # no state change: the label was never created, the policy untouched
        self.assertIsNone(st.try_get_value("/controls/keys/0/label"),
                          "an ungranted set effect changed state!")
        self.assertEqual(st.try_get_value("/policy/net/allow_hosts"), policy0,
                         "an ungranted set effect rewrote /policy!")
        logtxt = st.read_log(30000)
        self.assertIn("effect rejected (E_CAP)", logtxt)
        self.assertIn("CAPVIO get_reply ok=False code=E_CAP", logtxt)
        # the granted emit cap still works: plugin/capvio/hit arrived on the bus
        ev = self.wait_event("plugin/capvio/hit", timeout=10)
        self.assertEqual(ev["payload"], {"ok": True}, ev)
        self.assertTrue(st.daemon_alive(self.ipc))

    # ---- 040 filesystem traversal (T6) ---------------------------------------

    def test_plugins_040_fs_traversal_refused_E_CAP_nothing_read(self):
        st = Stack(self.bins)
        self.stack = st
        fsroot = st.tmp / "fsroot"
        fsroot.mkdir(parents=True)
        (fsroot / "ok.txt").write_text("inside-secret")
        secret = st.tmp / "secret.txt"
        secret.write_text("topsecret")
        manifest = make_manifest("fsprobe", ["state.write", "fs:%s" % fsroot],
                                 fs_roots=[str(fsroot)])
        behavior = {"mode": "fsprobe", "tag": "FSPROBE",
                    "outside": str(secret),
                    "traversal": "../../etc/shadow",
                    "inside": str(fsroot / "ok.txt")}
        install_plugin(st.xdg, manifest, behavior)
        st.start()
        c = st.ipc().hello_auth(st.token)
        c.subscribe("/deck/system/*")
        self.ipc = c
        topic = "app/abuse/fsprobe"
        self.kick(st, "fsprobe", topic)
        policy0 = st.try_get_value("/policy/net/allow_hosts")
        st.emit(self.ipc, topic)
        v = st.wait_plugin_pred(
            "fsprobe", lambda v: v["stats"]["violations"] >= 3,
            timeout=20, what="violations counted (2 fs requests + 1 out-of-subset set)")
        probe = {e["what"]: e for e in self.wait_probe(st, "fsprobe", 3)}
        # mediated fs requests outside the granted root are refused E_CAP; the
        # granted root is allowed (control)
        self.assertEqual(probe["fs:outside"]["code"], "E_CAP", probe["fs:outside"])
        self.assertEqual(probe["fs:traversal"]["code"], "E_CAP", probe["fs:traversal"])
        self.assertTrue(probe["fs:inside"]["ok"], probe["fs:inside"])
        # nothing was read outside the roots: the plugin's own direct read of the
        # outside file is denied by the Landlock layer (documented gap otherwise)
        direct = st.try_get_value("/plugins/fsprobe/state/direct")
        self.assertEqual(direct.get("inside"), "read_bytes=13", direct)
        if landlock_enforced(v):
            self.assertTrue(str(direct.get("outside", "")).startswith("denied:"),
                            "direct read outside fs_roots succeeded under Landlock: %s" % direct)
        # the set effect outside the writable subset was refused; policy unchanged
        self.assertEqual(st.try_get_value("/policy/net/allow_hosts"), policy0)
        # ...while the granted set inside the writable subset landed
        self.assertEqual(st.try_get_value("/controls/keys/5/label"), "fs-ok")
        self.assertGreaterEqual(v["stats"]["violations"], 3, v["stats"])
        self.assertTrue(st.daemon_alive(self.ipc))

    # ---- 050 oversized / malformed net URL + invalid manifest glob (T5/T11) ---

    def test_plugins_050_oversized_and_bad_net_url_refused_with_exact_codes(self):
        fake = FakeLights()
        self.fake = fake
        oversized = "http://lights.lan/" + "a" * 2100  # > NET_URL_MAX (2048) -> E_LIMIT
        st = self.boot([
            (make_manifest("netlim", ["state.write", "net:lights.lan"]),
             {"mode": "netprobe", "tag": "NETLIM",
              "urls": [oversized, "ftp://lights.lan/x", "http://",
                       "http://lights.lan/api/lamp"],
              "direct_host": "127.0.0.1", "direct_port": fake.port},
             None),
            # a net:<glob> the manifest schema cannot express ('/' is not in the
            # charset) — refused at manifest validation, the plugin never starts
            (make_manifest("badglob", ["state.write", "net:evil.com/path"]),
             {"mode": "netprobe", "tag": "BADGLOB", "urls": [],
              "direct_host": "127.0.0.1", "direct_port": fake.port},
             None),
        ])
        st.set_json("/policy/net/allow_hosts", ["lights.lan", "127.0.0.1"])
        topic = "app/abuse/netlim"
        self.kick(st, "netlim", topic)
        st.emit(self.ipc, topic)
        probe = {e["what"]: e for e in self.wait_probe(st, "netlim", 5, timeout=40)}
        self.assertEqual(probe[oversized]["code"], "E_LIMIT", probe[oversized])
        self.assertEqual(probe["ftp://lights.lan/x"]["code"], "E_SCHEMA", probe["ftp://lights.lan/x"])
        self.assertEqual(probe["http://"]["code"], "E_SCHEMA", probe["http://"])
        self.assertNotEqual(probe["http://lights.lan/api/lamp"].get("code"), "E_CAP",
                            "glob+policy-allowed host must not be E_CAP: %s"
                            % probe["http://lights.lan/api/lamp"])
        v = st.plugin_state("netlim")
        self.assertGreaterEqual(v["stats"]["violations"], 3, v["stats"])
        # the invalid-glob plugin was refused at manifest validation: no /plugins
        # entry, `get` is E_PATH, and invoking it is refused E_CAP (no host serves it)
        self.assertIsNone(st.plugin_state("badglob"))
        p = st.ds("get", "/plugins/badglob")
        self.assertEqual(p.returncode, 2, "expected exit 2 E_PATH, got rc=%d" % p.returncode)
        st.bind("app/abuse/badglob", "plugin badglob.go")
        st.emit(self.ipc, "app/abuse/badglob")
        err = st.wait_binding_error(self.ipc, 10)
        self.assertEqual(err["error"]["code"], "E_CAP", err)
        self.assertIn("no plugin host serves", err["error"]["message"], err)
        self.assertTrue(st.daemon_alive(self.ipc))

    # ---- 060 invoke timeout -> degraded -> restart (contract §5) --------------

    def test_plugins_060_invoke_timeout_degraded_then_restart(self):
        st = self.boot([
            # a benign plugin to boot the host without touching the hang plugin
            (make_manifest("booter", ["state.write"]),
             {"mode": "netprobe", "tag": "BOOT", "urls": [],
              "direct_host": "127.0.0.1", "direct_port": 1},
             None),
            (make_manifest("hang", ["state.write"]),
             {"mode": "hang", "tag": "HANG"},
             None),
        ])
        st.bind("app/abuse/boot", "plugin booter.go")
        st.emit(self.ipc, "app/abuse/boot")
        st.drain_events(self.ipc, 1.0)
        v = st.wait_plugin("hang", "running")
        pid0 = v["state"]["pid"]
        topic = "app/abuse/hang"
        # two steps: the hanging plugin step first, a set step after it
        st.bind(topic, "plugin hang.go", 'set /controls/keys/9/label "after"')
        # first timeout: E_LIMIT, plugin degraded, remaining steps still ran
        st.emit(self.ipc, topic)
        err = st.wait_binding_error(self.ipc, 15)
        self.assertEqual(err["error"]["code"], "E_LIMIT", err)
        self.assertEqual(err["step"], 0, err)
        v = st.wait_plugin("hang", "degraded", timeout=10)
        self.assertEqual(v["state"].get("timeouts"), 1, v["state"])
        self.assertEqual(st.try_get_value("/controls/keys/9/label"), "after",
                         "the set step after the failed plugin step must still run")
        self.assertTrue(st.daemon_alive(self.ipc))
        # second consecutive timeout: restart (new pid, restarts counted)
        st.emit(self.ipc, topic)
        err = st.wait_binding_error(self.ipc, 15)
        self.assertEqual(err["error"]["code"], "E_LIMIT", err)
        v = st.wait_plugin_pred(
            "hang",
            lambda v: v["status"] == "running" and v["stats"]["restarts"] >= 1
            and v["state"].get("pid") not in (None, pid0),
            timeout=30, what="restart with a new pid after the 2nd consecutive timeout")
        self.assertTrue(st.pid_gone(pid0), "the old hung pid %s is still alive" % pid0)
        self.assertEqual(st.try_get_value("/controls/keys/9/label"), "after")
        self.assertTrue(st.daemon_alive(self.ipc))

    # ---- 070 net glob edges (M5/S4/T11) ---------------------------------------

    def test_plugins_070_net_glob_edges_exact_matrix(self):
        fake = FakeLights()
        self.fake = fake
        lamp_url = "http://127.0.0.1:%d/api/lamp" % fake.port
        lan_urls = ["http://lights.lan/api/x", "http://lan/x",
                    "http://a.b.lan/x", "http://lights.lan.evil.com/x"]
        st = self.boot([
            (make_manifest("netwild", ["state.write", "net:*.lan"]),
             {"mode": "netprobe", "tag": "NETWILD", "urls": lan_urls,
              "direct_host": "127.0.0.1", "direct_port": fake.port}, None),
            (make_manifest("netexact", ["state.write", "net:lights.lan"]),
             {"mode": "netprobe", "tag": "NETEXACT",
              "urls": ["http://lights.lan/api/x", "http://lights.lan.evil.com/x",
                       "http://lan/x"],
              "direct_host": "127.0.0.1", "direct_port": fake.port}, None),
            (make_manifest("netsrv", ["state.write", "net:127.0.0.1"]),
             {"mode": "netprobe", "tag": "NETSRV", "urls": [lamp_url],
              "direct_host": "127.0.0.1", "direct_port": fake.port}, None),
        ])
        st.set_json("/policy/net/allow_hosts",
                    ["lights.lan", "lan", "a.b.lan", "lights.lan.evil.com", "127.0.0.1"])
        for pid in ("netwild", "netexact", "netsrv"):
            self.kick(st, pid, "app/abuse/%s" % pid)
            st.emit(self.ipc, "app/abuse/%s" % pid)
        st.drain_events(self.ipc, 1.0)
        wild = {e["what"]: e for e in self.wait_probe(st, "netwild", 5, timeout=45)}
        exact = {e["what"]: e for e in self.wait_probe(st, "netexact", 4, timeout=45)}
        srv = {e["what"]: e for e in self.wait_probe(st, "netsrv", 2, timeout=20)}
        # `*.lan` matches lights.lan but NOT lan, a.b.lan or lights.lan.evil.com
        self.assertNotEqual(wild["http://lights.lan/api/x"].get("code"), "E_CAP",
                            "*.lan must allow lights.lan: %s" % wild["http://lights.lan/api/x"])
        for u in ("http://lan/x", "http://a.b.lan/x", "http://lights.lan.evil.com/x"):
            self.assertEqual(wild[u]["code"], "E_CAP", "*.lan must deny %s: %s" % (u, wild[u]))
            self.assertIn("net:<glob>", wild[u].get("message") or "",
                          "denial must come from the glob layer: %s" % wild[u])
        # `lights.lan` (exact) matches only lights.lan
        self.assertNotEqual(exact["http://lights.lan/api/x"].get("code"), "E_CAP",
                            "lights.lan must allow lights.lan: %s"
                            % exact["http://lights.lan/api/x"])
        for u in ("http://lights.lan.evil.com/x", "http://lan/x"):
            self.assertEqual(exact[u]["code"], "E_CAP",
                             "exact lights.lan must deny %s: %s" % (u, exact[u]))
        # the allowed host succeeds end-to-end through the daemon-mediated path
        self.assertTrue(srv[lamp_url]["ok"], srv[lamp_url])
        self.assertEqual(srv[lamp_url]["status"], 200, srv[lamp_url])
        self.assertEqual(srv[lamp_url]["body"], "lamp-on", srv[lamp_url])
        # a raw socket opened by the plugin itself is denied (Landlock ABI>=4)
        if landlock_enforced(st.plugin_state("netsrv")):
            self.assertFalse(srv["direct-connect"]["ok"],
                             "the plugin opened a raw TCP socket itself: %s"
                             % srv["direct-connect"])
        self.assertTrue(st.daemon_alive(self.ipc))

    # ---- 080 crash -> respawn -> watchdog disable (T3, contract §9) -----------

    def test_plugins_080_crash_respawn_then_watchdog_disable(self):
        st = self.boot([
            (make_manifest("booter", ["state.write"]),
             {"mode": "netprobe", "tag": "BOOT", "urls": [],
              "direct_host": "127.0.0.1", "direct_port": 1},
             None),
            (make_manifest("crasher", ["state.write"]),
             {"mode": "crash", "tag": "CRASH"},
             None),
        ])
        st.bind("app/abuse/boot", "plugin booter.go")
        st.emit(self.ipc, "app/abuse/boot")
        st.drain_events(self.ipc, 1.0)
        st.wait_plugin("crasher", "running")
        topic = "app/abuse/crasher"
        st.bind(topic, "plugin crasher.go")
        # every invoke crashes the plugin mid-call -> E_DEVICE; the watchdog
        # respawns (<= 3 per 10 min) and then disables it
        for i in range(6):
            st.emit(self.ipc, topic)
            err = st.wait_binding_error(self.ipc, 10)
            self.assertEqual(err["error"]["code"], "E_DEVICE",
                             "crash mid-call must map to E_DEVICE: %s" % err)
            st.drain_events(self.ipc, 0.2)
        v = st.wait_plugin_pred(
            "crasher",
            lambda v: v["status"] == "stopped" and bool(v["state"].get("disabled_reason")),
            timeout=60, what="watchdog disable after 3 respawns within 600 s")
        self.assertIn("watchdog", v["state"]["disabled_reason"], v["state"])
        self.assertEqual(v["stats"]["restarts"], 3, v["stats"])
        # further invokes are refused: the plugin is stopped
        st.emit(self.ipc, topic)
        err = st.wait_binding_error(self.ipc, 10)
        self.assertEqual(err["error"]["code"], "E_DEVICE", err)
        self.assertIn("not running", err["error"]["message"], err)
        self.assertTrue(st.daemon_alive(self.ipc))


